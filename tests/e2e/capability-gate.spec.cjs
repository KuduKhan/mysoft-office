const {test,expect}=require('@playwright/test');
test('knowledge links connect Docs to Notes and survive browser restart',async({page})=>{
 await page.goto('/');
 await page.locator('[data-create="notes"]').first().click();
 await page.locator('#document-title').fill('Reference knowledge note');
 await page.keyboard.press('Control+s');
 await page.locator('[data-action="close-editor"]').click();
 await page.locator('[data-nav="home"]').first().click();
 await page.locator('[data-create="docs"]').first().click();
 await page.locator('[data-action="knowledge-links"]').click();
 await expect(page.getByRole('dialog',{name:'Knowledge links'})).toBeVisible();
 const select=page.locator('#knowledge-target');
 const option=select.locator('option',{hasText:'Reference knowledge note'});
 const id=await option.getAttribute('value');
 await select.selectOption(id);
 await page.locator('[data-action="knowledge-add"]').click();
 await expect(page.getByRole('dialog',{name:'Knowledge links'})).toContainText('Reference knowledge note');
 await page.locator('[data-action="modal-close"]').click();
 await page.keyboard.press('Control+s');await page.reload();
 await page.locator('[data-action="knowledge-links"]').click();
 await expect(page.getByRole('dialog',{name:'Knowledge links'})).toContainText('Reference knowledge note');
});
test('Media locked layer cannot be deleted, but can be unlocked',async({page})=>{
 await page.goto('/');await page.locator('[data-create="media"]').first().click();
 await page.locator('[data-media-action="drawing"]').click();
 await page.locator('#media-tool').selectOption('rect');
 const r=await page.locator('#media-canvas').boundingBox();
 await page.mouse.move(r.x+r.width*.2,r.y+r.height*.2);await page.mouse.down();
 await page.mouse.move(r.x+r.width*.6,r.y+r.height*.6);await page.mouse.up();
 await page.getByRole('tab',{name:'Layers',exact:true}).click();
 await page.locator('[data-media-action="layer-lock"]').click();
 await expect(page.locator('[data-media-action="layer-delete"]')).toBeDisabled();
 await expect(page.locator('#media-layer')).toContainText('(locked)');
 await page.keyboard.press('Control+s');await page.reload();
 await page.getByRole('tab',{name:'Layers',exact:true}).click();
 await page.locator('#media-layer').selectOption('0');
 await expect(page.locator('[data-media-action="layer-delete"]')).toBeDisabled();
 await page.locator('[data-media-action="layer-lock"]').click();
 await expect(page.locator('[data-media-action="layer-delete"]')).toBeEnabled();
});
