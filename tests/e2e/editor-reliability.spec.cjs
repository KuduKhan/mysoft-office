const {test,expect}=require('@playwright/test');
test.beforeEach(async({page})=>{
  await page.goto('/');
  await page.evaluate(()=>localStorage.clear());
  await page.reload();
});
test('Docs keeps header/footer and print paper settings without mutating rich content',async({page})=>{
  await page.locator('[data-create="docs"]').first().click();
  await page.locator('#rich-content').fill('Quarterly status');
  await page.locator('[data-ot-tab="Layout"]').click();
  page.once('dialog',d=>d.accept('Khaniversity learning'));
  await page.locator('[data-ot-action="page-header"]').click();
  page.once('dialog',d=>d.accept('Confidential draft'));
  await page.locator('[data-ot-action="page-footer"]').click();
  await expect(page.locator('.doc-paper-header')).toContainText('Khaniversity learning');
  await expect(page.locator('.doc-paper-footer')).toContainText('Confidential draft');
  await page.locator('[data-ot-input="paper"]').selectOption('Letter');
  await page.locator('[data-ot-input="orientation"]').selectOption('landscape');
  await page.locator('[data-ot-input="margins"]').selectOption('wide');
  await page.evaluate(()=>{window.print=()=>{window.__capturedPrint=document.getElementById('studio-dynamic-print-css')?.textContent;};});
  await page.locator('[data-ot-action="print"]').click();
  const css=await page.evaluate(()=>window.__capturedPrint);
  expect(css).toContain('size:Letter landscape');
  await page.reload();
  await expect(page.locator('.doc-paper-header')).toContainText('Khaniversity learning');
  await expect(page.locator('.doc-paper-footer')).toContainText('Confidential draft');
  await expect(page.locator('#rich-content')).toContainText('Quarterly status');
  await page.locator('[data-ot-tab="Layout"]').click();
  await expect(page.locator('[data-ot-input="orientation"]')).toHaveValue('landscape');
});
test('Sheets shows formula audit and dependency tracing on the Data ribbon',async({page})=>{
  await page.locator('[data-create="sheets"]').first().click();
  await page.locator('[data-cell="A1"]').fill('5');
  await page.locator('[data-cell="A1"]').press('Enter');
  await page.locator('[data-cell="B1"]').fill('=A1*2');
  await page.locator('[data-cell="B1"]').press('Enter');
  await page.locator('[data-cell="C1"]').fill('=9/0');
  await page.locator('[data-cell="C1"]').press('Enter');
  await page.locator('[data-ot-tab="Data"]').click();
  await page.locator('[data-ot-action="sheet-audit"]').click();
  await expect(page.getByText('Formula audit')).toBeVisible();
  await expect(page.locator('.studio-audit-table')).toContainText('#DIV/0!');
  await page.locator('[data-ot-action="settings-close"]').click();
  await page.locator('[data-cell="A1"]').click();
  await page.locator('[data-ot-action="sheet-trace"]').click();
  await expect(page.getByText('Cell trace: A1')).toBeVisible();
  await expect(page.getByText('Used by: B1')).toBeVisible();
});
test('Slides supports object alignment and resize without canvas overflow',async({page})=>{
  await page.locator('[data-create="slides"]').first().click();
  await page.locator('[data-ot-tab="Shapes"]').click();
  await page.locator('[data-ot-action="shape-rect"]').click();
  await page.locator('[data-ot-action="shape-align-center"]').click();
  await expect(page.locator('[data-slide-object]')).toHaveAttribute('style',/left:36\.5%/);
  const dimensions=['33','40'];let index=0;
  page.on('dialog',dialog=>dialog.accept(dimensions[index++]));
  await page.locator('[data-ot-action="shape-resize"]').click();
  await expect(page.locator('[data-slide-object]')).toHaveAttribute('style',/width:33%;height:40%/);
  await page.locator('[data-ot-action="shape-align-right"]').click();
  await expect(page.locator('[data-slide-object]')).toHaveAttribute('style',/left:67%/);
  await page.reload();
  await expect(page.locator('[data-slide-object]')).toHaveAttribute('style',/left:67%/);
});
test('Notes filters by notebook or note text and handles empty results on mobile',async({page})=>{
  await page.setViewportSize({width:390,height:790});
  await page.locator('[data-create="notes"]').first().click();
  await page.locator('#note-notebook').fill('Academy');
  await page.locator('#note-section').fill('Lecture');
  await page.locator('#rich-content').fill('Algorithms and data structures');
  await page.locator('[data-note-move]').click();
  await page.locator('#note-search').fill('Academy');
  await expect(page.locator('.note-list-item:not([hidden])')).toHaveCount(1);
  await page.locator('#note-search').fill('algorithm');
  await expect(page.locator('.note-list-item:not([hidden])')).toHaveCount(1);
  await page.locator('#note-search').fill('irrelevant-search');
  await expect(page.locator('#note-no-results')).toBeVisible();
  await expect(page.locator('.note-list-item:not([hidden])')).toHaveCount(0);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(391);
});
